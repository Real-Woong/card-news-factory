"""HTML → 본문 텍스트 추출.

3단계로 동작합니다.

1. **semantic 영역 우선**: ``<article>``, ``<main>``, ``[role=main]``,
   ``.post-content`` 등에서 본문으로 보이는 컨테이너를 찾아 그 안만 사용
2. **boilerplate 제거**: nav / header / footer / aside / form / script / style,
   그리고 class·id에 ``nav``, ``cookie``, ``share``, ``related``, ``newsletter``
   같은 패턴이 있는 요소 제거
3. **줄 단위 정리**: 반복 사이트 문구, 메뉴처럼 짧은 링크 나열, 쿠키 안내 문구
   제거 후 남은 문단만 연결

``beautifulsoup4``가 없으면 stdlib ``HTMLParser`` 기반 폴백을 쓰되, 같은 규칙을
가능한 범위에서 적용합니다. 어떤 경우에도 예외를 밖으로 내보내지 않습니다
(수집 한 건 때문에 런이 죽으면 안 됨).
"""

from __future__ import annotations

import re
from html.parser import HTMLParser

# 통째로 버리는 태그
DROP_TAGS = (
    "script",
    "style",
    "noscript",
    "template",
    "svg",
    "iframe",
    "form",
    "button",
    "nav",
    "header",
    "footer",
    "aside",
    "menu",
    "figure",
    "picture",
    "video",
    "audio",
    "canvas",
)

# class / id / role / aria-label 에 이 패턴이 있으면 버림
DROP_ATTR_PATTERN = re.compile(
    r"(^|[-_\s])("
    r"nav|navbar|navigation|menu|breadcrumb|sidebar|side-bar|"
    r"header|masthead|footer|site-footer|colophon|"
    r"cookie|consent|gdpr|privacy-banner|"
    r"share|sharing|social|follow|subscribe|newsletter|signup|sign-up|"
    r"related|recommend|recirc|more-stories|read-next|up-next|popular|trending|"
    r"comment|disqus|promo|banner|advert|advertisement|sponsor|"
    r"skip-link|screen-reader|sr-only|visually-hidden|"
    r"toc|table-of-contents|pagination|pager|tag-list|tags|byline-social|"
    r"modal|dialog|overlay|popup|toast|search|lang|language-select"
    r")([-_\s]|$)",
    re.IGNORECASE,
)

# 본문 컨테이너 후보 (앞에 있는 것이 우선)
CONTENT_SELECTORS = (
    "article",
    "main",
    "[role=main]",
    "[itemprop=articleBody]",
    ".article-body",
    ".article__body",
    ".post-content",
    ".post-body",
    ".entry-content",
    ".markdown-body",
    ".rich-text",
    ".prose",
    "#content",
    ".content",
)

# 줄 단위로 버리는 문구 (메뉴·쿠키·공유 버튼·위젯 잔여물)
LINE_NOISE = re.compile(
    r"^("
    r"share( this)?( on)?( (x|twitter|facebook|linkedin|reddit|email|copy link))?|"
    r"copy link|copied!?|print|"
    r"accept( all)?( cookies)?|reject( all)?|manage (cookies|preferences)|"
    r"we use cookies.*|this (site|website) uses cookies.*|cookie (policy|settings|notice).*|"
    r"subscribe( to.*)?|sign up( for.*)?|newsletter|"
    r"read (more|next)|related (posts|articles|reading)|more from .*|up next|"
    r"skip to (main )?content|back to top|back to [\w\s]{1,30}|"
    r"all rights reserved.*|©.*|copyright.*|"
    r"privacy policy|terms of (use|service)|cookie preferences|"
    r"follow us( on.*)?|table of contents|quick links|view all|"
    r"listen to (this )?article|\[\[.*\]\].*|"
    r"this content is generated by (google )?ai.*|"
    r"\d+\s*min(ute)?s?( \d+\s*sec(ond)?s?)?( read)?|"
    r"(english|한국어|日本語|中文|español|français|deutsch)"
    r")[\s.·|—-]*$",
    re.IGNORECASE,
)

_WS = re.compile(r"[ \t\u00a0]+")
_MENU_LIKE = re.compile(r"^[\w\s&'’/-]{1,24}$")

# semantic 컨테이너를 신뢰하는 최소 조건.
MIN_CONTAINER_CHARS = 200
# 컨테이너가 body 전체 텍스트의 이 비율 이상을 담아야 "본문"으로 인정.
CONTAINER_RATIO = 0.35


def _attr_haystack(attrs: dict[str, object] | None) -> str:
    """class/id/role 값을 하나의 문자열로 정규화.

    bs4 는 ``class`` 를 리스트로 돌려주므로(``['share-buttons']``) 그냥 str() 하면
    대괄호·따옴표가 붙어 단어 경계 패턴이 걸리지 않습니다.
    """
    if not attrs:
        return ""
    parts: list[str] = []
    for key in ("class", "id", "role", "aria-label", "data-testid", "itemprop"):
        value = attrs.get(key)
        if value is None:
            continue
        if isinstance(value, (list, tuple, set)):
            parts.extend(str(v) for v in value)
        else:
            parts.append(str(value))
    return " ".join(parts)


def _is_drop_attrs(attrs: dict[str, object] | None) -> bool:
    """class/id/role 등에 boilerplate 패턴이 있으면 True.

    bs4 는 decompose 된 노드에 대해 ``attrs`` 가 ``None`` 일 수 있으므로 방어합니다.
    """
    haystack = _attr_haystack(attrs)
    return bool(haystack.strip()) and bool(DROP_ATTR_PATTERN.search(haystack))


def _clean_lines(raw: str, *, drop_menu_like: bool = True) -> str:
    """줄 단위 노이즈 제거 후 재조합."""
    lines: list[str] = []
    for line in raw.splitlines():
        text = _WS.sub(" ", line).strip(" \u200b\t·|•")
        if not text:
            continue
        if LINE_NOISE.match(text):
            continue
        # 한 단어~짧은 구절만 연속으로 나오면 메뉴일 가능성이 큼.
        if drop_menu_like and _MENU_LIKE.match(text) and " " not in text.strip():
            continue
        lines.append(text)

    # 같은 줄이 반복되는 사이트 boilerplate 제거 (순서 유지)
    deduped: list[str] = []
    seen: dict[str, int] = {}
    for line in lines:
        key = line.lower()
        seen[key] = seen.get(key, 0) + 1
        if seen[key] > 1 and len(line) < 200:
            continue
        deduped.append(line)
    return "\n".join(deduped).strip()


# --------------------------------------------------------------------------- #
# BeautifulSoup 경로
# --------------------------------------------------------------------------- #
def _extract_with_bs4(html: str) -> str | None:
    try:
        from bs4 import BeautifulSoup  # type: ignore[import-not-found]
    except ImportError:
        return None

    soup = BeautifulSoup(html, "html.parser")

    for tag in soup(list(DROP_TAGS)):
        tag.decompose()

    # 본문 컨테이너와 그 조상은 절대 제거하지 않습니다. 이 보호가 없으면
    # 상위 wrapper 의 class 하나가 패턴에 걸려 페이지 전체가 사라집니다
    # (실측: openai.com/news 가 0자로 추출됨).
    protected: set[int] = set()
    try:
        for element in soup.select(", ".join(CONTENT_SELECTORS)):
            protected.add(id(element))
            protected.update(id(parent) for parent in element.parents)
    except Exception:  # noqa: BLE001 - selector 지원 차이 방어
        pass

    for tag in soup.find_all(True):
        if id(tag) in protected:
            continue
        try:
            if _is_drop_attrs(getattr(tag, "attrs", None)):
                tag.decompose()
        except Exception:  # noqa: BLE001 - 잘못된 마크업으로 attrs 접근이 깨질 수 있음
            continue

    body_text = _clean_lines((soup.body or soup).get_text("\n"))

    # semantic 후보 중 "가장 많은 본문을 담은" 것을 고릅니다. 첫 매치를 쓰면
    # 사이트마다 <article> 이 껍데기이거나 요약 카드일 때 본문을 잃습니다.
    best_text = ""
    for selector in CONTENT_SELECTORS:
        try:
            candidates = soup.select(selector)
        except Exception:  # noqa: BLE001
            continue
        for found in candidates:
            text = _clean_lines(found.get_text("\n"))
            if len(text) > len(best_text):
                best_text = text

    # 후보가 본문의 일부만 담고 있으면(JS 렌더링 페이지의 빈 <article> 등)
    # 정리된 body 전체를 씁니다.
    if len(best_text) >= MIN_CONTAINER_CHARS and len(best_text) >= len(body_text) * CONTAINER_RATIO:
        return best_text
    return body_text


# --------------------------------------------------------------------------- #
# stdlib 폴백
# --------------------------------------------------------------------------- #
class _FallbackExtractor(HTMLParser):
    """bs4가 없을 때 쓰는 최소 추출기. DROP_TAGS / 속성 규칙을 함께 적용."""

    _BLOCK = {
        "p", "div", "br", "li", "h1", "h2", "h3", "h4", "h5", "h6",
        "tr", "section", "article", "blockquote", "pre",
    }

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self._parts: list[str] = []
        self._skip_depth = 0
        self._skip_tag: str | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attr_map = {k: (v or "") for k, v in attrs}
        if self._skip_depth:
            if tag == self._skip_tag:
                self._skip_depth += 1
            return
        if tag in DROP_TAGS or _is_drop_attrs(attr_map):
            self._skip_depth = 1
            self._skip_tag = tag
            return
        if tag in self._BLOCK:
            self._parts.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if self._skip_depth and tag == self._skip_tag:
            self._skip_depth -= 1
            if self._skip_depth == 0:
                self._skip_tag = None
            return
        if not self._skip_depth and tag in self._BLOCK:
            self._parts.append("\n")

    def handle_data(self, data: str) -> None:
        if not self._skip_depth:
            self._parts.append(data)

    def text(self) -> str:
        return _clean_lines("".join(self._parts))


def _extract_with_stdlib(html: str) -> str:
    parser = _FallbackExtractor()
    try:
        parser.feed(html)
        parser.close()
    except Exception:  # noqa: BLE001 - 깨진 마크업이 런을 죽이면 안 됨
        return _clean_lines(re.sub(r"<[^>]+>", "\n", html))
    return parser.text()


def _strip_tags(html: str) -> str:
    """최후 폴백: 태그만 제거하고 줄 정리."""
    return _clean_lines(re.sub(r"<[^>]+>", "\n", html), drop_menu_like=False)


def html_to_text(html: str) -> str:
    """HTML에서 본문 텍스트만 추출합니다.

    Args:
        html: 원본 HTML (부분 조각도 허용).

    Returns:
        정리된 평문. 어떤 단계가 실패해도 예외를 던지지 않고, 가능한 한 텍스트를
        반환합니다(추출 결과가 비면 태그 제거 폴백을 씁니다).
    """
    if not html or not html.strip():
        return ""

    result = ""
    try:
        bs_result = _extract_with_bs4(html)
        if bs_result is not None:
            result = bs_result
    except Exception:  # noqa: BLE001 - bs4 내부 오류도 폴백으로 흡수
        result = ""

    if not result:
        try:
            result = _extract_with_stdlib(html)
        except Exception:  # noqa: BLE001
            result = ""

    # 정리 규칙이 과하게 걸려 전부 사라진 경우를 대비한 안전망.
    if not result:
        result = _strip_tags(html)
    return result
